// Token Radar — the value model (radar-2).
//
// A protocol that records no token gets an implied value from the snapshot's
// own figures only: its TVL, its seven-day TVL change, how long it has run
// with no token, its category and how many chains it runs on. No protocol
// name is ever special-cased; the same function scores every row.
//
//   base      = tvl_usd x 0.25
//   growth    = clamp(change_7d, -60, 120)
//   growthMult = 1 + growth / 100 x 0.5
//   maturity  = 0.6 + min(age_days, 1095) / 1095 x 0.4
//   category  = 0.95 .. 1.15 by what the protocol does (see categoryMultiple)
//   chains    = 0.95 for one chain, 1.00 for 2-3, 1.05 for 4-7, 1.08 for 8+
//   youth     = 0.85 under 90 days old, 0.93 under 180, 0.98 under a year
//   decline   = 0.80 when 7d growth is below -25%, 0.90 below -10%
//   implied   = round(base x growthMult x maturity x category x chains
//                      x youth x decline), at least $1
//
// Age is days from listed_at to the snapshot's as_of; an unknown age counts
// as 365 days for maturity and takes no youth penalty. After scoring, rows
// are sorted by implied value and any tie is nudged down by at least $1 so
// the board's values never rise with rank; the raw pre-nudge value is kept
// on the row so the dashboard can show the tie-break honestly.

/** One protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

